/**
 * Question pools for the Math screen (app/math.tsx).
 *
 * Each question-based game keeps a pool of 50 questions. Every time a game
 * starts (or is restarted) a random round of `*_ROUND_LENGTH` questions is
 * drawn from its pool with `pickRandomQuestions` (utils/question-pool.ts).
 *
 * Kept free of path aliases / React Native imports so plain Node can load it.
 */

